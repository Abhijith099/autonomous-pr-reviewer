import logging
import time
from sqlalchemy import text
from app.db.session import engine
from app.github.client import GitHubClient
from app.agents.security_agent import SecurityAgent
from app.schemas import ReviewState, Finding

logger = logging.getLogger("pr_reviewer.orchestrator")


class ReviewOrchestrator:
    """Coordinates the entire pull request review workflow end-to-end."""

    def __init__(self):
        self.github = GitHubClient()
        self.security_agent = SecurityAgent()

    def _build_markdown_comment(self, state: ReviewState) -> str:
        """Converts findings into a clean GitHub Markdown comment."""
        pr = state.pr
        findings = state.findings

        if not findings:
            return f"""### :] Autonomous PR Review: Security Check Passed

Hello @{pr.author}! 👋

Our automated security analysis reviewed **{len(pr.changed_files)}** changed file(s) and found **no security vulnerabilities**.

> *Generated by Autonomous Multi-Agent PR Reviewer • Human review recommended.*
"""

        # Group findings by severity
        lines = [
            f"### :] Autonomous PR Review: Security Findings Detected",
            f"**Target PR:** #{pr.pr_number} — `{pr.pr_title}`",
            f"**Files Reviewed:** {len(pr.changed_files)}",
            "",
            "---",
        ]

        critical = [f for f in findings if f.severity in ["critical", "high"]]
        medium_low = [f for f in findings if f.severity in ["medium", "low", "info"]]

        if critical:
            lines.append("#### :< High & Critical Risks T_T")
            for f in critical:
                lines.append(f"- **`{f.file}`** (line ~{f.line_hint or 'N/A'})")
                lines.append(f"  - **Issue:** {f.issue}")
                lines.append(f"  - **Recommendation:** {f.recommendation}")
                lines.append(f"  - *Confidence: {int(f.confidence * 100)}%*")
            lines.append("")

        if medium_low:
            lines.append("#### Medium & Low Concerns ;D")
            for f in medium_low:
                lines.append(f"- **`{f.file}`**: {f.issue}")
                lines.append(f"  - *Fix:* {f.recommendation}")
            lines.append("")

        lines.append("---")
        lines.append(
            "> ⚠️ *This automated review assists human reviewers. Please verify before merging.*"
        )
        return "\n".join(lines)

    async def _save_run_to_db(self, state: ReviewState, latency_ms: int):
        """Persists the review run and findings to PostgreSQL."""
        try:
            async with engine.begin() as conn: #if anything fails it rollsback instead of half completed tranaction
                # 1. Ensure repository exists in DB
                repo_res = await conn.execute(
                    text(
                        """
                        INSERT INTO repositories (github_repo_id, full_name, owner, name)
                        VALUES (:repo_id, :full_name, :owner, :name)
                        ON CONFLICT (full_name) DO UPDATE SET updated_at = NOW()
                        RETURNING id;
                    """
                    ),
                    {
                        "repo_id": 1,  # Placeholder or GitHub ID
                        "full_name": state.pr.repo_full_name,
                        "owner": state.pr.repo_full_name.split("/")[0],
                        "name": state.pr.repo_full_name.split("/")[1]
                        if "/" in state.pr.repo_full_name
                        else state.pr.repo_full_name,
                    },
                )
                repo_id = repo_res.scalar_one()

                # 2. Ensure pull_request exists in DB
                pr_res = await conn.execute(
                    text(
                        """
                        INSERT INTO pull_requests (
                            repository_id, github_pr_id, pr_number, title, body, author_login,
                            base_branch, head_branch, head_sha, state
                        )
                        VALUES (
                            :repo_id, :pr_id, :pr_num, :title, :body, :author,
                            :base_branch, :head_branch, :head_sha, 'open'
                        )
                        ON CONFLICT (repository_id, pr_number) DO UPDATE SET
                            title = EXCLUDED.title,
                            head_sha = EXCLUDED.head_sha,
                            updated_at = NOW()
                        RETURNING id;
                    """
                    ),
                    {
                        "repo_id": repo_id,
                        "pr_id": state.pr.pr_number,
                        "pr_num": state.pr.pr_number,
                        "title": state.pr.pr_title,
                        "body": state.pr.pr_description,
                        "author": state.pr.author,
                        "base_branch": state.pr.base_branch,
                        "head_branch": state.pr.head_branch,
                        "head_sha": state.pr.head_sha,
                    },
                )
                db_pr_id = pr_res.scalar_one()

                # 3. Insert review_run
                run_res = await conn.execute(
                    text(
                        """
                        INSERT INTO review_runs (
                            pull_request_id, trigger_action, status, latency_ms,
                            total_files_changed, completed_at
                        )
                        VALUES (
                            :pr_id, 'opened', :status, :latency_ms, :files_count, NOW()
                        )
                        RETURNING id;
                    """
                    ),
                    {
                        "pr_id": db_pr_id,
                        "status": state.status,
                        "latency_ms": latency_ms,
                        "files_count": len(state.pr.changed_files),
                    },
                )
                review_run_id = run_res.scalar_one()

                # 4. Insert each finding
                for f in state.findings:
                    await conn.execute(
                        text(
                            """
                            INSERT INTO findings (
                                review_run_id, agent_name, severity, category,
                                file_path, line_hint, issue, recommendation, confidence
                            )
                            VALUES (
                                :run_id, :agent, :severity, :cat, :file, :line, :issue, :rec, :conf
                            );
                        """
                        ),
                        {
                            "run_id": review_run_id,
                            "agent": f.agent,
                            "severity": f.severity,
                            "cat": f.category,
                            "file": f.file,
                            "line": f.line_hint,
                            "issue": f.issue,
                            "rec": f.recommendation,
                            "conf": f.confidence,
                        },
                    )

            logger.info(
                f"Successfully logged review run {review_run_id} and {len(state.findings)} findings to Neon DB."
            )
        except Exception as e:
            logger.error(f"Failed to record review in database: {e}", exc_info=True)

    async def execute_review(
        self, repo_full_name: str, pr_number: int
    ) -> ReviewState:
        """Executes the full review lifecycle."""
        start_time = time.time()
        logger.info(f"Starting review pipeline for {repo_full_name} PR #{pr_number}")

        try:
            # 1. Fetch PR Context from GitHub
            pr_context = await self.github.get_pr_context(repo_full_name, pr_number)

            state = ReviewState(pr=pr_context, status="reviewing")

            # 2. Run Security Agent review
            findings = await self.security_agent.review(pr_context.changed_files)
            state.findings = findings

            # 3. Build Markdown comment
            markdown_comment = self._build_markdown_comment(state)
            state.final_comment = markdown_comment

            # 4. Post comment to GitHub
            try:
                await self.github.post_pr_comment(
                    repo_full_name, pr_number, markdown_comment
                )
                logger.info(f"Successfully posted PR review comment to GitHub!")
            except Exception as e:
                logger.warning(
                    f"Could not post comment to GitHub (check token permissions): {e}"
                )

            state.status = "completed"
            latency_ms = int((time.time() - start_time) * 1000)

            # 5. Persist run and findings to PostgreSQL
            await self._save_run_to_db(state, latency_ms)

            return state

        except Exception as e:
            logger.error(f"Review pipeline failed: {e}", exc_info=True)
            latency_ms = int((time.time() - start_time) * 1000)
            return ReviewState(
                pr=None,  # type: ignore
                status="failed",
                error_message=str(e),
            )
